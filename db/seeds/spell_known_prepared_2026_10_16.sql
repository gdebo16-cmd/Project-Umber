WITH ch AS (
  SELECT c.id, COALESCE(sc.cantrips, cc.cantrips) AS cantrips, COALESCE(sc.spells, cc.spells) AS spells
    FROM characters c
    LEFT JOIN classes cl ON cl.id = c.class_id
    LEFT JOIN sub_classes s ON s.id = c.subclass_id
    LEFT JOIN caps sc ON sc.is_sub AND sc.name = lower(trim(s.name)) AND sc.level = LEAST(30, GREATEST(1, c.level))
    LEFT JOIN caps cc ON NOT cc.is_sub AND cc.name = lower(trim(cl.name)) AND cc.level = LEAST(30, GREATEST(1, c.level))
), ranked AS (
  SELECT cs.id, s.base_level, ch.cantrips, ch.spells,
         ROW_NUMBER() OVER (PARTITION BY cs.character_id, (s.base_level = 0) ORDER BY s.base_level, s.name, cs.id) AS rn
    FROM character_spells cs JOIN spells s ON s.id = cs.spell_id JOIN ch ON ch.id = cs.character_id
   WHERE cs.is_learned
)
UPDATE character_spells cs SET is_prepared = CASE
    WHEN r.spells IS NULL THEN true
    WHEN r.base_level = 0 THEN r.rn <= r.cantrips
    ELSE r.rn <= r.spells END
  FROM ranked r WHERE r.id = cs.id;
COMMIT;
