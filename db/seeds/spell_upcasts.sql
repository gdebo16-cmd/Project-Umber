-- SRD rows only; homebrew upcasts live in homebrew_rework.sql.
-- Idempotent: CREATE IF NOT EXISTS + ON CONFLICT DO UPDATE.
BEGIN;
CREATE TABLE IF NOT EXISTS spell_upcasts (
  id            SERIAL PRIMARY KEY,
  spell_id      INT NOT NULL REFERENCES spells(id) ON DELETE CASCADE,
  cast_level    INT NOT NULL CHECK (cast_level BETWEEN 1 AND 15),
  damage_dice   TEXT,
  heal_dice     TEXT,
  extra_targets INT,
  duration      TEXT,
  notes         TEXT,
  UNIQUE (spell_id, cast_level)
);
